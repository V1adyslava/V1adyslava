def score_by_level(answers: list[int]) -> dict[int, int]:
    """Возвращает словарь {уровень: 0..100} на основе списка ответов длины 25.

    answers[i] — выбранный вариант (1..4) для вопроса QUESTIONS[i].
    """
    if len(answers) != len(QUESTIONS):
        raise ValueError(f"Ожидалось {len(QUESTIONS)} ответов, получено {len(answers)}")

    per_level: dict[int, list[float]] = {i: [] for i in range(1, 8)}
    for question, answer in zip(QUESTIONS, answers):
        per_level[question["level"]].append((answer - 1) / 3)

    return {lvl: round(sum(vals) / len(vals) * 100) for lvl, vals in per_level.items()}
